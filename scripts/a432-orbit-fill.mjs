#!/usr/bin/env node
/**
 * Every prefix of the kernel's doubling orbit has a module at its address.
 *
 * `a432:names` found three addresses with nothing at them — 1.2.4, 1.2.4.8 and
 * 1.2.4.8.7. The space held the seed, the first step, and then jumped to the
 * closed six-cycle, so the middle of the orbit was unaddressed.
 *
 * These are not written by hand. The family is a template: `a432.1.ts`,
 * `a432.1.2.ts` and `a432.1.2.4.8.7.5.ts` are the same module with one number
 * changed, and hand-copying it three more times would be three more places for
 * the sixth edit to miss. The template is READ from the shortest existing
 * member rather than pasted here, so a change to that file propagates instead
 * of drifting — the same rule the rest of this repository holds generated
 * artifacts to.
 *
 * THE ORBIT IS READ FROM THE KERNEL. Add a digit to VORTEX_ORBIT and a new
 * address appears; nothing here lists 1, 2, 4, 8, 7, 5.
 *
 *   npm run a432:orbit
 *   npm run a432:orbit:check
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const A432 = join(ROOT, 'src/0/3/6/9/1/2/4/8/7/5/1')
const CHECK = process.argv.includes('--check')

const { VORTEX_ORBIT } = await import(join(ROOT, 'src/kernel/index.ts'))
const orbit = [...VORTEX_ORBIT]
if (orbit.length === 0) {
  console.error('a432:orbit FAIL — the kernel exports an empty orbit, so there are no addresses to fill')
  process.exit(1)
}

/** The address for a prefix of length n, and the file that holds it. */
const STAMP = '// GENERATED by scripts/a432-orbit-fill.mjs from the shortest existing member; do not edit by hand.\n'
const addressOf = (n) => orbit.slice(0, n).join('.')
const fileOf = (n) => join(A432, `a432.${addressOf(n)}.ts`)

/**
 * The template, read from the shortest member that exists. Its length literal
 * and its sequence comment are the only things that vary across the family, so
 * they are the only things substituted.
 */
const donorLength = [...Array(orbit.length).keys()]
  .map((i) => i + 1)
  .find((n) => existsSync(fileOf(n)) && readFileSync(fileOf(n), 'utf8').includes('openDoublingVortexStream'))
if (donorLength === undefined) {
  console.error('a432:orbit FAIL — no existing orbit module to take the template from; refusing to invent one')
  process.exit(1)
}
const donor = readFileSync(fileOf(donorLength), 'utf8')

function moduleFor(n) {
  const address = addressOf(n)
  const seq = orbit.slice(0, n)
  let out = donor
  // The header names the file and the sequence it holds.
  out = out.replace(/^\/\/ a432\.[\d.]+\.ts — .*$/m, `// a432.${address}.ts — Open Vortex/Doubling Stream Module`)
  out = out.replace(/encodes the open doubling sequence \([\d-]+\)/, `encodes the open doubling sequence (${seq.join('-')})`)
  out = out.replace(/^ \* - The sequence [^\n]*$/m, ` * - The sequence ${seq.join('→')} is the open right-hand vortex in vortex math, truncated before closure.`)
  out = out.replace(/^ \* - It is [^\n]*$/m, ' * - It is the journey, the generative flow, the living stream before closure or return.')
  out = out.replace(/It is the seed of the vortex, the origin point\./, 'It is the generative arc of the vortex, not yet returned to origin.')
  // The length literal, in both places it appears, and the worked example.
  out = out.replace(/length = \d+\)/g, `length = ${n})`)
  out = out.replace(/\/\/ \[[\d,]*\]/, `// [${seq.join(',')}]`)
  out = out.replace(/doubling vortex \([\d-]+\)/, `doubling vortex (${seq.join('-')})`)
  // THE STAMP IS PART OF THE TEMPLATE, not something the writer adds afterwards.
  // It was appended at write time and omitted here, so every generated member
  // compared unequal to its own template and the check reported all three as
  // drifted the moment they were written.
  return out.replace(/^(\/\/ a432\.[\d.]+\.ts — [^\n]*\n)/, `$1${STAMP}`)
}

/**
 * THE HANDLES MUST BE LOADABLE, or they are not handles.
 *
 * These seven modules are imported by nothing: they all export the same names,
 * so `a432.index.ts` cannot re-export them, and the ratchet counted every one
 * as reachable from no static entry. That is the correct measurement of the
 * wrong thing — an address module is meant to be reached BY ADDRESS.
 *
 * So the family gets a loader keyed by address. The paths are string literals
 * because that is what a static reader can follow; a computed specifier would
 * load the same module and leave it invisible to every tool that reads the
 * import graph, which is how a module becomes unreachable while being used.
 *
 * Generated from the orbit alongside the modules themselves, so an address can
 * never exist without a way to load it.
 */
const LOADER = join(A432, 'a432.orbit.ts')
function loaderModule() {
  const rows = []
  for (let n = 1; n <= orbit.length; n += 1) {
    rows.push(`  '${addressOf(n)}': () => import('./a432.${addressOf(n)}.ts'),`)
  }
  return `// a432.orbit.ts — every address on the doubling orbit, loadable by name
${STAMP}//
// The orbit modules all export the same names, so they cannot be re-exported
// from a432.index.ts. They are reached by ADDRESS instead: this is the map from
// an address to the module that holds it, with literal paths so a static reader
// can follow them.

/** Every address on the orbit, shortest first. */
export const ORBIT_ADDRESSES = [
${Array.from({ length: orbit.length }, (_, i) => `  '${addressOf(i + 1)}',`).join('\n')}
] as const

export type OrbitAddress = typeof ORBIT_ADDRESSES[number]

/** Load the module at an address. The name is the handle; this unpacks it. */
export const ORBIT_HANDLES: Record<string, () => Promise<unknown>> = {
${rows.join('\n')}
}

/**
 * Load an address and return the sequence it holds. A handle carries its load
 * implicitly, so this is the whole of what "reading" one means.
 */
export async function loadOrbitAddress(address: string): Promise<readonly number[]> {
  const handle = ORBIT_HANDLES[address]
  if (handle === undefined) throw new Error(\`a432.orbit: no handle at address \${address}\`)
  const mod = await handle() as { getOpenDoublingSequence?: () => number[] }
  const seq = mod.getOpenDoublingSequence?.()
  if (seq === undefined) throw new Error(\`a432.orbit: the module at \${address} holds no sequence\`)
  return seq
}
`
}

const missing = []
for (let n = 1; n <= orbit.length; n += 1) if (!existsSync(fileOf(n))) missing.push(n)

if (CHECK) {
  const wrong = []
  for (let n = 1; n <= orbit.length; n += 1) {
    if (!existsSync(fileOf(n))) { wrong.push(`${addressOf(n)} — no file at this address`); continue }
    // Only the generated members are held to the template; the donor and any
    // hand-written member are not rewritten by this tool and not judged by it.
    const text = readFileSync(fileOf(n), 'utf8')
    if (!text.includes('GENERATED by scripts/a432-orbit-fill.mjs')) continue
    if (text !== moduleFor(n)) wrong.push(`${addressOf(n)} — has drifted from the template`)
  }
  /**
   * AND EVERY ADDRESS MUST LOAD ITSELF, which is the law the whole family is
   * for. A handle carries its load implicitly, so `a432.1.2.4` is not a module
   * named after the sequence 1-2-4 — it is that sequence, and asking it returns
   * it. A module at the right address holding the wrong sequence is a broken
   * handle, and nothing else in this repository would notice.
   */
  for (let n = 1; n <= orbit.length; n += 1) {
    if (!existsSync(fileOf(n))) continue
    const address = addressOf(n)
    let loaded = null
    try {
      const mod = await import(fileOf(n))
      loaded = mod.getOpenDoublingSequence?.() ?? null
    } catch (err) {
      wrong.push(`${address} — will not import: ${String(err.message).slice(0, 60)}`)
      continue
    }
    if (loaded === null) continue // a hand-written member with a different shape
    if (loaded.join('.') !== address) wrong.push(`${address} — loads ${JSON.stringify(loaded)}, which is not its own address`)
  }

  if (wrong.length > 0) {
    console.error('a432:orbit:check FAIL — the orbit is not fully addressed:')
    for (const w of wrong) console.error(`  ${w}`)
    console.error('  run npm run a432:orbit')
    process.exit(1)
  }
  if (!existsSync(LOADER) || readFileSync(LOADER, 'utf8') !== loaderModule()) {
    console.error('a432:orbit:check FAIL — a432.orbit.ts is missing or has drifted from the orbit; run npm run a432:orbit')
    process.exit(1)
  }
  console.log(`a432:orbit:check ok — every prefix of ${orbit.join('-')} has a module, each loads its own address, and all ${orbit.length} are reachable through a432.orbit.ts`)
  process.exit(0)
}

writeFileSync(LOADER, loaderModule())

if (missing.length === 0) {
  console.log(`a432:orbit ok — all ${orbit.length} prefixes of ${orbit.join('-')} addressed, and a432.orbit.ts loads them`)
  process.exit(0)
}

for (const n of missing) {
  writeFileSync(fileOf(n), moduleFor(n))
  console.log(`  wrote a432.${addressOf(n)}.ts — the open sequence ${orbit.slice(0, n).join('-')}`)
}
console.log(`a432:orbit — ${missing.length} address(es) filled from the template in a432.${addressOf(donorLength)}.ts`)
