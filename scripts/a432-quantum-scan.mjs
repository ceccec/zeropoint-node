#!/usr/bin/env node
/**
 * Quantum scan of every a432.* file, as a gated projection.
 *
 * Uses the repo's own apparatus: each file is content-addressed
 * (computeContentUuid), its fingerprint lifted to a qubit (encodeQuantumState
 * from quantum-fold-cipher), and the whole corpus folded into one root
 * (merkleFold). The census numbers come from importExportGraphTip.
 *
 * The scan is a projection of the bytes on disk — regenerate with
 * `npm run a432:scan`; any change to any a432.* file moves the corpus root and
 * fails `npm run a432:scan:check`. Not a hand inventory.
 *
 * Regenerate: npm run a432:scan · verify: npm run a432:scan:check
 */

import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname, join, relative, extname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { digitalRoot, merkleFold } from '../src/0/index.ts'
import { computeContentUuid } from '../src/integrity/content-uuid.ts'
import { encodeQuantumState } from '../src/security/quantum-fold-cipher.ts'
import { importExportGraphTip } from '../src/kernel/import-graph.ts'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = join(root, 'src')
const outPath = join(root, 'docs', 'A432_QUANTUM_SCAN.md')

/** Every a432.* file under src/, sorted for deterministic output. */
function walk(dir) {
  const out = []
  for (const name of readdirSync(dir).sort()) {
    const abs = join(dir, name)
    if (statSync(abs).isDirectory()) out.push(...walk(abs))
    else if (name.startsWith('a432.')) out.push(abs)
  }
  return out
}

// UUID → qubit: sum the hex nibbles; digital-root is the vortex digit (1–9),
// first-nibble parity picks the basis, sum parity the measured value.
function qubitFromUuid(uuid, idx) {
  const hex = uuid.replace(/-/g, '')
  let sum = 0
  for (const c of hex) sum += parseInt(c, 16)
  const basis = parseInt(hex[0], 16) % 2 ? 'X' : 'Z'
  return { digit: digitalRoot(sum), state: encodeQuantumState(basis, sum % 2, idx) }
}

const files = walk(srcDir).sort()
const byExt = {}
const spectrum = Object.fromEntries([...Array(10).keys()].map((d) => [d, 0]))
const basis = { Z: 0, X: 0 }
const value = { 0: 0, 1: 0 }
const contentSeen = new Map()
const leaves = []

for (const [idx, abs] of files.entries()) {
  const rel = relative(root, abs)
  const content = readFileSync(abs, 'utf8')
  const ext = extname(abs).slice(1) || 'none'
  byExt[ext] = (byExt[ext] || 0) + 1

  const contentUuid = String(computeContentUuid({ kind: 'a432-content', content }))
  if (!contentSeen.has(contentUuid)) contentSeen.set(contentUuid, [])
  contentSeen.get(contentUuid).push(rel)

  const fileUuid = String(computeContentUuid({ kind: 'a432-file', path: rel, content }))
  leaves.push(fileUuid)
  const q = qubitFromUuid(fileUuid, idx)
  spectrum[q.digit] += 1
  basis[q.state.basis] += 1
  value[q.state.value] += 1
}

const duplicates = [...contentSeen.values()].filter((paths) => paths.length > 1)
const quantumRoot = merkleFold(leaves)
const census = importExportGraphTip()

// Extension summary in a fixed order (descending count, then name) for determinism.
const extLine = Object.entries(byExt)
  .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
  .map(([e, n]) => `${e}=${n}`)
  .join(' · ')

const model = {
  kind: 'a432-quantum-scan',
  files: files.length,
  byExt,
  spectrum,
  basis,
  value,
  duplicateGroups: duplicates.length,
  quantumRoot,
  censusRoot: census.root,
}
const receipt = String(computeContentUuid(model))

const digits = [1, 2, 3, 4, 5, 6, 7, 8, 9]
const spectrumHeader = `| ${digits.join(' | ')} |`
const spectrumDivider = `| ${digits.map(() => '--:').join(' | ')} |`
const spectrumRow = `| ${digits.map((d) => spectrum[d]).join(' | ')} |`

const lines = [
  '<!-- GENERATED by scripts/a432-quantum-scan.mjs — do not edit by hand. Run: npm run a432:scan -->',
  '',
  '# A432 quantum scan',
  '',
  'Computed scan of every `a432.*` file: each is content-addressed, its fingerprint',
  'lifted to a qubit, and the corpus folded into one root. Not a hand inventory —',
  'regenerate with `npm run a432:scan`; drift fails `npm run a432:scan:check`.',
  '',
  `- files scanned: **${files.length}**`,
  `- by extension: \`${extLine}\``,
  `- byte-identical duplicate groups: **${duplicates.length}**`,
  `- corpus quantum root: \`${quantumRoot}\``,
  `- import/export census: files=${census.fileCount} · edges=${census.edgeCount} · exports=${census.exportCount} · root=\`${census.root}\``,
  `- scan receipt: \`${receipt}\``,
  '',
  '## Vortex-digit spectrum',
  '',
  "Each file's content-uuid folds to a digital root of its hex nibbles. The root is",
  'always 1–9, so the void digit 0 is structurally empty.',
  '',
  spectrumHeader,
  spectrumDivider,
  spectrumRow,
  '',
  '## Quantum register',
  '',
  'Each fingerprint is lifted to a qubit via `encodeQuantumState`: first-nibble',
  'parity picks the basis, nibble-sum parity the measured value.',
  '',
  `- basis: \`Z=${basis.Z} · X=${basis.X}\``,
  `- value: \`0=${value[0]} · 1=${value[1]}\``,
  '',
  '## Boundary',
  '',
  'Content-addressing and digital-root folding over source bytes. No claim outside',
  'arithmetic; the qubit encoding is a labelling of hashes, not a physical measurement.',
  '',
]
const next = lines.join('\n')

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(outPath, 'utf8')
  } catch {
    console.error('docs/A432_QUANTUM_SCAN.md missing — run npm run a432:scan')
    process.exit(1)
  }
  if (current !== next) {
    console.error('A432_QUANTUM_SCAN.md drift — run npm run a432:scan')
    process.exit(1)
  }
  console.log('a432:scan:check ok', files.length, 'files', quantumRoot)
  process.exit(0)
}

writeFileSync(outPath, next)
console.log('wrote docs/A432_QUANTUM_SCAN.md', files.length, 'files', quantumRoot)
