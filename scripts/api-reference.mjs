#!/usr/bin/env node
/**
 * The API reference, generated from the API.
 *
 * The hand-written docs/API_REFERENCE.md documented 32 functions. 28 of them —
 * 87% — do not exist anywhere in src/. It is linked from the site nav as "API
 * reference", so a reader following it wrote code against getChallengeMetadata,
 * analyzeConsciousnessState and 26 others that were never there, or were
 * removed and the document never noticed.
 *
 * A reference that is 87% fiction is worse than no reference: it costs the
 * reader the time to discover it is wrong, and it looks authoritative while
 * doing so. Documented error codes like INVALID_FREQUENCY and CALCULATION_ERROR
 * do not exist either.
 *
 * So it is generated from the package's declared entry points — the exports
 * map in package.json, which is the API by definition, since that is what a
 * consumer can import. Nothing here can drift: if an export is renamed, this
 * file changes on the next run, and --check fails if it was not regenerated.
 *
 *   npm run api:reference        write docs/API_REFERENCE.md
 *   npm run api:reference:check  fail if it has drifted
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname, join, relative } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { createHash } from 'node:crypto'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'docs/API_REFERENCE.md')
const CHECK = process.argv.includes('--check')

const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))

/**
 * THE FILTER HAD EMPTIED THIS FILE, AND THE CHECK AGREED WITH IT.
 *
 * This kept only subpaths whose target ends in `.ts`. Every one of the 24
 * entry points resolves to `./dist/*.esm.js`, so the filter dropped all of
 * them, the reference documented 0 exports across 0 entry points, and
 * api:reference:check compared an empty page against an empty generation and
 * reported ok. A generator that reads nothing produces a page that contradicts
 * nothing — the same failure this repository already refuses in parity (0
 * tools), shadowed (0 shipped exports) and families (0 definitions), which is
 * why the guard below is not optional.
 *
 * The built ESM is also the more honest thing to read: it is what a consumer
 * imports. The chain builds before it documents.
 */
const entries = Object.entries(pkg.exports ?? {})
  .map(([subpath, spec]) => [subpath, typeof spec === 'string' ? spec : spec?.import])
  .filter(([subpath, target]) => typeof target === 'string' && subpath !== './package.json')

if (entries.length === 0) {
  console.error('api:reference FAIL — read 0 entry points from package.json exports, so this page would')
  console.error('  document nothing and its check would pass against nothing.')
  process.exit(1)
}

const sections = []
for (const [subpath, target] of entries.sort()) {
  const file = join(ROOT, target)
  let mod
  try { mod = await import(pathToFileURL(file).href) } catch (e) {
    sections.push({ subpath, target, error: e.message.split('\n')[0], items: [] })
    continue
  }
  const items = []
  for (const [name, value] of Object.entries(mod).sort()) {
    if (name === 'default') continue
    const kind = typeof value === 'function'
      ? (/^class\s/.test(String(value)) ? 'class' : `function (${value.length} arg${value.length === 1 ? '' : 's'})`)
      : Array.isArray(value) ? `array (${value.length})`
        : value === null ? 'null' : typeof value
    items.push({ name, kind })
  }
  sections.push({ subpath, target, error: null, items })
}

const total = sections.reduce((s, x) => s + x.items.length, 0)
if (total === 0) {
  console.error(`api:reference FAIL — ${entries.length} entry point(s) yielded 0 exports between them.`)
  for (const x of sections.filter((y) => y.error)) console.error(`  ${x.subpath} -> ${x.target}: ${x.error}`)
  console.error('  A reference of nothing agrees with every page, including a wrong one. Run npm run build first.')
  process.exit(1)
}
const lines = []
lines.push('# API reference')
lines.push('')
lines.push('<!-- GENERATED by scripts/api-reference.mjs — do not edit. Run npm run api:reference. -->')
lines.push('')
lines.push('Every entry below is an export that exists, read from the modules named in')
lines.push("`package.json`'s `exports` map — which is the API by definition, because it is")
lines.push('what a consumer can import. Nothing here is written by hand.')
lines.push('')
lines.push('The previous version of this file was hand-written and documented 32 functions,')
lines.push('28 of which did not exist in the source. A reference that is 87% fiction costs a')
lines.push('reader more than no reference at all, because it looks authoritative while it')
lines.push('misleads them.')
lines.push('')
lines.push(`**${total} exports across ${sections.length} entry points.**`)
lines.push('')
for (const s of sections) {
  lines.push(`## \`${pkg.name}${s.subpath === '.' ? '' : s.subpath.slice(1)}\``)
  lines.push('')
  lines.push(`Source: \`${s.target}\``)
  lines.push('')
  if (s.error) {
    lines.push(`> This entry point could not be loaded: ${s.error}`)
    lines.push('')
    continue
  }
  if (s.items.length === 0) {
    lines.push('> No runtime exports (types only).')
    lines.push('')
    continue
  }
  lines.push('| export | kind |')
  lines.push('| --- | --- |')
  for (const it of s.items) lines.push(`| \`${it.name}\` | ${it.kind} |`)
  lines.push('')
}
const body = lines.join('\n')
const digest = createHash('sha256').update(body).digest('hex').slice(0, 12)
const doc = `${body}\n<!-- digest ${digest} -->\n`

if (CHECK) {
  let current = ''
  try { current = readFileSync(OUT, 'utf8') } catch { /* missing */ }
  if (current !== doc) {
    console.error('api:reference:check FAIL — docs/API_REFERENCE.md has drifted from the exports; run npm run api:reference')
    process.exit(1)
  }
  console.log(`api:reference:check ok — ${total} exports, digest ${digest}`)
  process.exit(0)
}
writeFileSync(OUT, doc)
console.log(`api:reference wrote ${relative(ROOT, OUT)} — ${total} exports across ${sections.length} entry points, digest ${digest}`)
process.exit(0)
