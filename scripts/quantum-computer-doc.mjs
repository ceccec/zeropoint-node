#!/usr/bin/env node
/**
 * The quantum computer, documented from its own measurements.
 *
 * This package carries four representations of a quantum state, six exact
 * modules, three MCP tools and a set of measurements about what all of it
 * costs — and a person who installed it could find none of that. The README
 * describes digit arithmetic; the quantum surface was reachable only by
 * reading the source.
 *
 * EVERY NUMBER ON THE PAGE IS READ FROM A RECORD, never typed. The counts of
 * identified algorithms, the oracle-call laws, the state-vector-against-tableau
 * timings and the list of what was NOT measured all come from the JSON that
 * `npm run impostors`, `npm run query:cost` and `npm run capacity` write. A
 * hand-written copy of a measurement is the defect this repository keeps
 * finding, most recently an MCP server reporting its version as a literal five
 * minors stale.
 *
 *   npm run quantum:doc
 *   npm run quantum:doc:check
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PAGE = join(ROOT, 'docs/QUANTUM_COMPUTER.md')
const CHECK = process.argv.includes('--check')

/**
 * ABSENT AND UNREADABLE ARE DIFFERENT, and collapsing them is worse than not
 * checking at all. This returned null for both, and the caller then called the
 * record "missing" and told you to run the tool that writes it — true and
 * actionable when the file is not there, and a LIE that sends you to regenerate
 * a file you already have when it is corrupt or half-written.
 *
 * A verifier whose failure mode is indistinguishable from a documented
 * limitation tests less than nothing, because the limitation is reassuring.
 * (uuidna-27's phrasing, after four ordinary bugs hid behind one honest-sounding
 * "cannot decide this" produced by a caught throw returning null.)
 */
const read = (f) => {
  const p = join(ROOT, 'src/verification', f)
  if (!existsSync(p)) return { absent: true }
  try { return { record: JSON.parse(readFileSync(p, 'utf8')) } } catch (err) {
    return { unreadable: String(err).split('\n')[0] }
  }
}

const loaded = [
  ['impostors.json', read('impostors.json'), 'npm run impostors'],
  ['query-cost.json', read('query-cost.json'), 'npm run query:cost'],
  ['quantum-capacity.json', read('quantum-capacity.json'), 'npm run capacity'],
  ['shor-exhaustive.json', read('shor-exhaustive.json'), 'npm run shor:exhaustive'],
  ['qpu-pentagram.json', read('qpu-pentagram.json'), 'npm run qpu:pentagram'],
]
const unreadable = loaded.filter(([, v]) => v.unreadable)
const absent = loaded.filter(([, v]) => v.absent)
if (unreadable.length > 0) {
  console.error('quantum:doc FAIL — these records EXIST and could not be parsed. That is corruption, not a')
  console.error('  missing measurement, and regenerating them would destroy whatever is wrong with them:')
  for (const [k, v] of unreadable) console.error(`    ${k}: ${v.unreadable}`)
  process.exit(1)
}
if (absent.length > 0) {
  console.error('quantum:doc FAIL — these records are absent; this page states measurements and will not invent them:')
  for (const [k, , cmd] of absent) console.error(`    ${k} — ${cmd}`)
  process.exit(1)
}

const [impostors, cost, capacity, shor, qpu] = loaded.map(([, v]) => v.record)

/** Bytes as GiB, for the one place the page names a capacity. */
const gib = (b) => `${(b / 1024 ** 3).toFixed(0)} GiB`
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))
const server = readFileSync(join(ROOT, 'src/mcp/server.ts'), 'utf8')

const quantumTools = [...server.matchAll(/name: '(zeropoint\.quantum\w+)',\s*\n\s*description:\s*([\s\S]*?),\s*\n\s*inputSchema/g)]
  .map((m) => ({
    name: m[1],
    description: m[2].split('\n').map((l) => l.trim().replace(/^\+\s*/, '')).join(' ')
      .replace(/^'|'$/g, '').replace(/'\s*'/g, '').trim(),
  }))
if (quantumTools.length === 0) {
  console.error('quantum:doc FAIL — read 0 quantum tools from src/mcp/server.ts')
  process.exit(1)
}

const identified = (impostors.results ?? []).filter((r) => r.expectedCaught).map((r) => r.algorithm)
const answerOnly = (impostors.results ?? []).filter((r) => !r.expectedCaught).map((r) => r.algorithm)
const rows = capacity.stateVectorVsStabilizer ?? []
const beyond = capacity.stabilizerBeyondStateVector ?? []

