/**
 * A GENERATOR THAT PRODUCED NOTHING MUST NOT EXIT 0. An edit to this file once
 * stripped every newline from it, leaving one line that node read as a shebang
 * and nothing else — so the script did nothing, printed nothing, and exited 0.
 * `quantum:doc:check` would have passed in the gate chain while checking no
 * page at all, which is the same shape as the null this file already refuses.
 */
if (page.length < 2000 || L.filter((l) => l.startsWith('| ')).length < 8) {
  console.error(`quantum:doc FAIL — produced ${page.length} bytes and ${L.filter((l) => l.startsWith('| ')).length} table rows,`)
  console.error('  which is too little to be the page. Refusing to write or approve it.')
  process.exit(1)
}

if (CHECK) {
  if (!existsSync(PAGE) || readFileSync(PAGE, 'utf8') !== page) {
    console.error('quantum:doc:check FAIL — docs/QUANTUM_COMPUTER.md has drifted from the measurements; run npm run quantum:doc')
    process.exit(1)
  }
  console.log(`quantum:doc:check ok — ${quantumTools.length} tools, ${impostors.identifiedByMethod} identified by method, page matches the records`)
  process.exit(0)
}

writeFileSync(PAGE, page)
